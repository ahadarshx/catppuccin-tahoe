#!/usr/bin/env python3
"""Draws Tune's icons from one geometry:

  hicolor/scalable/apps/io.github.rice.Tune.svg           colour app icon (grid, dock)
  hicolor/symbolic/apps/io.github.rice.Tune-symbolic.svg  one-colour icon (inside the app)

The mark is a note (round head, stem, curled flag) with two sound waves on a
shared centre. Stem, flag and waves share one stroke width with round ends.
Everything is emitted as filled outlines, because GTK only recolours fills
in symbolic icons.

Usage: python3 data/icons/make-icons.py   (from the Tune folder)
"""
import math
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
W = 1.08                 # stroke width of stem, flag and waves (16.933 grid)
LIFT = -0.42             # optical centring: the head is heavier than the top

HEAD = dict(cx=6.28, cy=11.42, rx=1.98, ry=1.56, angle=-22)
STEM_X, STEM_TOP, STEM_BOTTOM = 7.78, 4.05, 11.05
FLAG = [(7.78, 4.05), (9.55, 4.25), (10.95, 5.25), (10.95, 6.85)]
WAVE_CENTRE = (8.95, 11.32)
WAVES = [(1.95, 52), (3.45, 50)]    # (radius, half angle in degrees)
# At 16px two waves blur together; the symbolic icon keeps one, between them.
SYMBOLIC_WAVES = [(2.75, 50)]


def fmt(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def cubic(p, t):
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = p
    u = 1 - t
    return (u**3 * x0 + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t**3 * x3,
            u**3 * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t**3 * y3)


def thick_curve(points):
    """Outline of a polyline drawn with width W; the round ends are
    separate circles (see `round_ends`)."""
    r = W / 2
    normals = []
    for i, (x, y) in enumerate(points):
        a = points[max(i - 1, 0)]
        b = points[min(i + 1, len(points) - 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        length = math.hypot(dx, dy) or 1
        normals.append((-dy / length, dx / length))
    left = [(x + nx * r, y + ny * r) for (x, y), (nx, ny) in zip(points, normals)]
    right = [(x - nx * r, y - ny * r) for (x, y), (nx, ny) in zip(points, normals)]
    outline = left + list(reversed(right))
    return "M" + "L".join(f"{fmt(x)} {fmt(y)}" for x, y in outline) + "Z"


def round_ends(*points):
    return "".join(f'<circle cx="{fmt(x)}" cy="{fmt(y)}" r="{fmt(W / 2)}"/>' for x, y in points)


def wave(radius, half_angle):
    """A ring segment opening to the right, with round ends."""
    cx, cy = WAVE_CENTRE
    a = math.radians(half_angle)
    ro, ri = radius + W / 2, radius - W / 2
    po = lambda rad, ang: (cx + rad * math.cos(ang), cy + rad * math.sin(ang))
    (x1, y1), (x2, y2) = po(ro, -a), po(ro, a)
    (x3, y3), (x4, y4) = po(ri, a), po(ri, -a)
    ring = (f'<path d="M{fmt(x1)} {fmt(y1)}A{fmt(ro)} {fmt(ro)} 0 0 1 {fmt(x2)} {fmt(y2)}'
            f'L{fmt(x3)} {fmt(y3)}A{fmt(ri)} {fmt(ri)} 0 0 0 {fmt(x4)} {fmt(y4)}Z"/>')
    return ring + round_ends(po(radius, -a), po(radius, a))


def mark(waves=WAVES):
    """The glyph as SVG elements, in the 16.933 grid."""
    h = HEAD
    head = (f'<ellipse cx="{fmt(h["cx"])}" cy="{fmt(h["cy"])}" rx="{fmt(h["rx"])}" ry="{fmt(h["ry"])}" '
            f'transform="rotate({h["angle"]} {fmt(h["cx"])} {fmt(h["cy"])})"/>')
    stem = f'<path d="{thick_curve([(STEM_X, STEM_BOTTOM), (STEM_X, STEM_TOP)])}"/>'
    flag_points = [cubic(FLAG, i / 32) for i in range(33)]
    flag = f'<path d="{thick_curve(flag_points)}"/>' + round_ends(flag_points[0], flag_points[-1])
    rings = "".join(wave(r, a) for r, a in waves)
    return f'<g transform="translate(0 {LIFT})">{head}{stem}{flag}{rings}</g>'


SQUIRCLE = ("M5.36 1.058c-1.53 0-2.577.457-3.26 1.2-.678.74-1.042 1.8-1.042 3v6.416c0 1.2.364 2.261 1.042 3.001"
            ".683.744 1.73 1.2 3.26 1.2h6.23c1.53 0 2.579-.456 3.26-1.2.68-.74 1.025-1.703 1.025-3V5.5"
            "c0-1.57-.345-2.502-1.024-3.242-.682-.743-1.73-1.2-3.26-1.2H6.745z")
RIM = ("M5.36 1.058c-1.53 0-2.577.457-3.26 1.2-.678.74-1.042 1.8-1.042 3.001v6.415c0 1.2.364 2.26 1.043 3 "
       ".682.744 1.73 1.2 3.26 1.2h6.23c1.53 0 2.577-.456 3.26-1.2.678-.739 1.024-1.702 1.024-3V5.5"
       "c0-1.57-.346-2.502-1.024-3.242-.683-.743-1.73-1.2-3.26-1.2H6.745zm0 .264h6.232c1.477 0 2.437.432 3.064 1.116"
       ".634.69.954 1.53.954 3.062v6.174c0 1.251-.322 2.134-.954 2.822-.627.684-1.587 1.114-3.064 1.114H5.359"
       "c-1.477 0-2.437-.43-3.064-1.114-.625-.682-.973-1.675-.973-2.822V5.26c0-1.148.348-2.14.973-2.822"
       ".627-.684 1.587-1.116 3.064-1.116")


def app_icon():
    # The same squircle, rim and shadow recipe as MacTahoe's own app icons.
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 16.933 16.933">
  <!-- Generated by make-icons.py -->
  <defs>
    <linearGradient id="bg" x1="8.466" x2="8.466" y1="1.058" y2="15.875" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#c6a0ff"/>
      <stop offset="1" stop-color="#7838ee"/>
    </linearGradient>
    <linearGradient id="glyph" x1="8.466" x2="8.466" y1="3.4" y2="13.4" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#fff"/>
      <stop offset="1" stop-color="#eee3ff"/>
    </linearGradient>
    <linearGradient id="rim" x1="6.745" x2="10.583" y1="1.058" y2="11.312" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#fff"/>
      <stop offset="1" stop-color="#fff" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="rim2" x1="15.081" x2="12.7" y1="14.816" y2="12.171" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#fff"/>
      <stop offset="1" stop-color="#fff" stop-opacity="0"/>
    </linearGradient>
    <filter id="soft" width="1.024" height="1.024" x="-.012" y="-.012" color-interpolation-filters="sRGB">
      <feGaussianBlur stdDeviation=".074"/>
    </filter>
    <filter id="shadow" width="1.5" height="1.5" x="-.25" y="-.25" color-interpolation-filters="sRGB">
      <feGaussianBlur stdDeviation=".42"/>
    </filter>
  </defs>
  <path fill="url(#bg)" d="{SQUIRCLE}"/>
  <g filter="url(#soft)" opacity=".45">
    <path fill="url(#rim)" fill-rule="evenodd" d="{RIM}"/>
    <path fill="url(#rim2)" fill-rule="evenodd" d="{RIM}"/>
  </g>
  <g fill="#2b0870" opacity=".24" filter="url(#shadow)" transform="translate(0 .4)">{mark()}</g>
  <g fill="url(#glyph)">{mark()}</g>
</svg>
'''


def symbolic_icon():
    # The glyph's bounds, fitted to the 16px grid with a pixel of margin.
    scale = 1.32
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16">
  <!-- Generated by make-icons.py; GTK recolours it to the theme's text colour. -->
  <g fill="#2e3436" transform="translate(8 8) scale({scale}) translate(-8.3 -8.55)">{mark(SYMBOLIC_WAVES)}</g>
</svg>
'''


(HERE / "hicolor/scalable/apps/io.github.rice.Tune.svg").write_text(app_icon())
(HERE / "hicolor/symbolic/apps/io.github.rice.Tune-symbolic.svg").write_text(symbolic_icon())
print("wrote both icons")
